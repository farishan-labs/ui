import { mkdirSync, writeFileSync, readFileSync } from "node:fs";
import { resolve } from "node:path";

const ROOT = resolve(import.meta.dir, "..");
const SRC_TOKENS = resolve(ROOT, "src/tokens");
const DIST = resolve(ROOT, "dist");

type TokenNode = { $value?: unknown; $type?: string; [k: string]: unknown };

function isToken(node: unknown): node is { $value: unknown } {
  return typeof node === "object" && node !== null && "$value" in (node as object);
}

function walk(node: TokenNode, path: string[], out: { path: string[]; value: unknown }[]): void {
  if (isToken(node)) {
    out.push({ path, value: node.$value });
    return;
  }
  if (typeof node === "object" && node !== null) {
    for (const [k, v] of Object.entries(node)) {
      if (k.startsWith("$")) continue;
      walk(v as TokenNode, [...path, k], out);
    }
  }
}

function cssVarName(path: string[]): string {
  return "--ui-" + path.join("-");
}

function buildNested(entries: { path: string[]; value: unknown }[]): unknown {
  const root: Record<string, unknown> = {};
  for (const { path, value } of entries) {
    let cur: Record<string, unknown> = root;
    for (let i = 0; i < path.length - 1; i++) {
      const key = path[i]!;
      if (typeof cur[key] !== "object" || cur[key] === null) cur[key] = {};
      cur = cur[key] as Record<string, unknown>;
    }
    cur[path[path.length - 1]!] = value;
  }
  return root;
}

const raw = JSON.parse(readFileSync(resolve(SRC_TOKENS, "tokens.json"), "utf8")) as TokenNode;
const entries: { path: string[]; value: unknown }[] = [];
walk(raw, [], entries);

// CSS
const cssLines: string[] = [":root {"];
for (const { path, value } of entries) {
  cssLines.push(`  ${cssVarName(path)}: ${value};`);
}
cssLines.push("}");
cssLines.push("");
const css = cssLines.join("\n");

// TS
const nested = buildNested(entries);
const ts = `// Generated by scripts/gen-tokens.ts — do not edit by hand.
// Source: src/tokens/tokens.json (W3C DTCG).

export const tokens = ${JSON.stringify(nested, null, 2)} as const;

export type Tokens = typeof tokens;

export const cssVar = (path: string[]): string => "--ui-" + path.join("-");
`;

mkdirSync(SRC_TOKENS, { recursive: true });
writeFileSync(resolve(SRC_TOKENS, "tokens.css"), css);
writeFileSync(resolve(SRC_TOKENS, "tokens.ts"), ts);

mkdirSync(DIST, { recursive: true });
writeFileSync(resolve(DIST, "tokens.css"), css);

console.log(
  `Generated ${entries.length} tokens -> src/tokens/tokens.css, src/tokens/tokens.ts, dist/tokens.css`,
);
